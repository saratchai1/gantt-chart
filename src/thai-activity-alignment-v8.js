export function thaiLocalizationStats(rows){
  const byStatus={};let thaiPrimary=0,reviewRequired=0,plan01ReviewRequired=0;
  for(const row of rows){
    const status=row.translation_status||'UNCLASSIFIED';byStatus[status]=(byStatus[status]||0)+1;
    if(THAI_RE.test(row.activity_name||''))thaiPrimary++;
    if(status==='REVIEW_REQUIRED'){reviewRequired++;if(row.plan_no==='01')plan01ReviewRequired++;}
  }
  return {total:rows.length,thai_primary:thaiPrimary,review_required:reviewRequired,plan01_review_required:plan01ReviewRequired,by_status:byStatus};
}
