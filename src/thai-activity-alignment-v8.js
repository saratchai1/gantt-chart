function translateArea(value){
  const original=String(value||'Project-wide');
  if(AREA_TH[original])return AREA_TH[original];
  const inst=original.match(/^Installment\s+(\d+)$/i);if(inst)return `งวดงานที่ ${inst[1]}`;
  const area=original.match(/^Area\s+([A-D])$/i);if(area)return `พื้นที่ ${area[1]}`;
  const areas=original.match(/^Areas\s+(.+)$/i);if(areas)return `พื้นที่ ${areas[1]}`;
  return original.replace(/Cluster\s+(\d+)/gi,'กลุ่มที่ $1');
}

